package com.pixplaze.api.web.data.server;

/**
 * Уровень интеграции сервера с нашей системой.
 *
 * <ul>
 *   <li>{@link #NONE} — владелец зарегистрировал сервер, но НЕ ставил наш плагин: показываем
 *       только указанную им базовую информацию (БД) + online-данные протокола (если доступны).
 *   <li>{@link #PLUGIN} — установлен наш плагин: дополнительно доступны специфические данные
 *       (TPS, uptime, детальные списки игроков и т.п.), которые сервер присылает нам сам (push).
 * </ul>
 */
public enum IntegrationType {
    NONE,
    PLUGIN
}
